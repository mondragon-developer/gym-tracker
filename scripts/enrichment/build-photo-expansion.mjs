// Rebuild the reviewed still-photo batch. Cached bytes must match the research manifest.
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';

const selection = JSON.parse(await fs.readFile('scripts/enrichment/photo-selection.json', 'utf8'));
const research = JSON.parse(await fs.readFile('docs/research/exercise-expansion/manifest.json', 'utf8'));
const root = 'public/exercise-media/photos';
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const records = [];
// Validate every input before writing the batch.
for (const entry of selection) {
  const candidate = research.photoCandidates.find(row => row.sourceId === entry.sourceId);
  if (!candidate?.status.startsWith('preferred')) throw new Error(`Unapproved photo pair: ${entry.sourceId}`);
  const images = [];
  for (const [index, source] of candidate.images.entries()) {
    let bytes;
    const cache = `temp/exercise-research-media/${entry.sourceId}-${index}.jpg`;
    try { bytes = await fs.readFile(cache); } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      const response = await fetch(source.url);
      if (!response.ok) throw new Error(`${source.url}: HTTP ${response.status}`);
      bytes = Buffer.from(await response.arrayBuffer());
    }
    if (hash(bytes) !== source.sha256 || bytes.length !== source.bytes) throw new Error(`Source mismatch: ${cache}`);
    images.push({ bytes, source, path: `${entry.id}-${index}.jpg` });
  }
  if (images.length !== 2 || images[0].source.sha256 === images[1].source.sha256) throw new Error(`Invalid pair: ${entry.id}`);
  records.push({ entry, images });
}
await fs.mkdir(root, { recursive: true });
for (const { images } of records) for (const image of images) await fs.writeFile(`${root}/${image.path}`, image.bytes);
await fs.copyFile('public/exercise-media/functional/LICENSE.txt', `${root}/LICENSE.txt`);
await fs.writeFile(`${root}/provenance.json`, JSON.stringify({
  repository: research.source.repository, revision: research.source.revision,
  license: research.source.licenseDeclared, licenseUrl: research.source.licenseUrl,
  modifications: 'Original JPEG files copied without image modifications. Names, bilingual instructions and photo descriptions edited by Gym Tracker.',
  exercises: records.map(({ entry, images }) => ({ id: entry.id, name: entry.name, sourceId: entry.sourceId,
    images: images.map(({ path, source }) => ({ path, ...source })) }))
}, null, 2) + '\n');
const metadata = selection.map(({ id, name, nameEs, muscleGroup, equipment, functional }) => ({ id, name, nameEs, muscleGroup, equipment, functional }));
const details = Object.fromEntries(selection.map(({ id, sourceId, equipment, target, secondaryMuscles, instructions, photoDescriptions }) => [id, {
  source: 'free-exercise-db', sourceId, equipment, target, secondaryMuscles, instructions, photoDescriptions
}]));
await fs.writeFile('src/data/photoExercises.js', '// Generated by scripts/enrichment/build-photo-expansion.mjs. Stable IDs, lightweight catalog metadata.\nexport const PHOTO_EXERCISES = ' + JSON.stringify(metadata, null, 2) + ';\n');
await fs.writeFile('src/data/photoEnrichment.js', '// Generated by scripts/enrichment/build-photo-expansion.mjs. Loaded only when instructions are requested.\nexport const PHOTO_ENRICHMENT = ' + JSON.stringify(details, null, 2) + ';\n');
console.log(`Verified and packaged ${selection.length} exercises and ${records.length * 2} original photos.`);
