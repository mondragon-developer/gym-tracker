// Rebuild reviewed video excerpts. Requires FFmpeg and FFprobe on PATH.
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const selection = JSON.parse(await fs.readFile('scripts/enrichment/sport-selection.json', 'utf8'));
const output = 'public/exercise-media/sports';
const cache = 'temp/exercise-research-media';
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const probe = file => JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration:stream=codec_type,codec_name,width,height', '-of', 'json', file], { encoding: 'utf8', windowsHide: true }));
await fs.mkdir(cache, { recursive: true });
// Verify all originals before producing any shipped files.
for (const { source, clip } of selection) {
  const file = `${cache}/${source.file}`;
  let bytes;
  try { bytes = await fs.readFile(file); } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    const response = await fetch(source.url);
    if (!response.ok) throw new Error(`Download failed: ${source.url} (${response.status})`);
    bytes = Buffer.from(await response.arrayBuffer());
    if (hash(bytes) === source.sha256 && bytes.length === source.bytes) await fs.writeFile(file, bytes);
  }
  if (hash(bytes) !== source.sha256 || bytes.length !== source.bytes) throw new Error(`Source mismatch: ${source.file}`);
  const metadata = probe(file);
  const video = metadata.streams.find(stream => stream.codec_type === 'video');
  if (!video || clip.width > video.width || clip.start < 0 || clip.start + clip.duration > Number(metadata.format.duration)) throw new Error(`Invalid excerpt: ${source.file}`);
}
await fs.mkdir(output, { recursive: true });
const provenance = [];
for (const entry of selection) {
  const { id, source, clip } = entry;
  const videoPath = `${output}/${id}.mp4`;
  const posterPath = `${output}/${id}.jpg`;
  execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', '-ss', String(clip.start), '-i', `${cache}/${source.file}`, '-t', String(clip.duration), '-map', '0:v:0', '-an', '-vf', `scale=${clip.width}:-2,setsar=1`, '-c:v', 'libx264', '-preset', 'medium', '-crf', '23', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', videoPath], { windowsHide: true });
  execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', '-ss', String(clip.posterTime), '-i', videoPath, '-frames:v', '1', '-q:v', '3', posterPath], { windowsHide: true });
  const metadata = probe(videoPath);
  if (metadata.streams.some(stream => stream.codec_type === 'audio')) throw new Error(`Unexpected audio: ${id}`);
  const files = await Promise.all([videoPath, posterPath].map(async path => {
    const bytes = await fs.readFile(path);
    return { path: path.slice(output.length + 1), bytes: bytes.length, sha256: hash(bytes) };
  }));
  provenance.push({ id, name: entry.name, source, clip, output: metadata, files,
    modifications: 'Excerpt trimmed at the recorded timestamps; audio removed; transcoded to H.264; soccer footage reduced to 720 pixels wide; poster extracted. No mirroring, generated frames or speed changes. Boxing video and poster adaptations remain CC BY-SA 2.5 Colombia.' });
}
await fs.writeFile(`${output}/provenance.json`, JSON.stringify({ reviewed: '2026-11-06', exercises: provenance }, null, 2) + '\n');
await fs.writeFile(`${output}/LICENSES.txt`, selection.map(({ id, source }) => `${id}.mp4 and ${id}.jpg\n${source.title}\nAuthor: ${source.author}\nSource: ${source.page}\nLicense: ${source.license}\n${source.licenseUrl}\nChanges: trimmed, silent H.264 excerpt and extracted poster; soccer footage downscaled. Boxing adaptations, including the English/Spanish descriptions and instructions, are distributed under CC BY-SA 2.5 Colombia. No endorsement implied.\n`).join('\n'));
const metadata = selection.map(({ id, name, nameEs, muscleGroup, equipment, activity, clip }) => ({ id, name, nameEs, muscleGroup, equipment, activity, videoWidth: clip.width }));
const details = Object.fromEntries(selection.map(({ id, equipment, source, instructions, description }) => [id, {
  source: 'sports-video', equipment, instructions, description,
  attribution: { author: source.author, title: source.title, url: source.page, license: source.license, licenseUrl: source.licenseUrl }
}]));
await fs.writeFile('src/data/sportExercises.js', '// Generated by scripts/enrichment/build-sport-media.mjs. Stable catalog IDs.\nexport const SPORT_EXERCISES = ' + JSON.stringify(metadata, null, 2) + ';\n');
await fs.writeFile('src/data/sportEnrichment.js', '// Generated by scripts/enrichment/build-sport-media.mjs. Loaded on demand.\nexport const SPORT_ENRICHMENT = ' + JSON.stringify(details, null, 2) + ';\n');
console.log(`Verified ${selection.length} original sources and built ${selection.length} silent clips with posters.`);
