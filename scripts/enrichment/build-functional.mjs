// Reproducible, pinned import. GIFs alternate the original two photos; they do
// not synthesize intermediate movement or claim to show complete technique.
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const revision = 'f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5';
const root = `https://raw.githubusercontent.com/yuhonas/free-exercise-db/${revision}`;
const selection = JSON.parse(await fs.readFile('scripts/enrichment/functional-selection.json', 'utf8'));
const out = 'public/exercise-media/functional';
await fs.mkdir(out, { recursive: true });
await fs.mkdir('temp/functional-frames', { recursive: true });
async function download(path) {
  const response = await fetch(`${root}/${path}`);
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}
const dataset = JSON.parse((await download('dist/exercises.json')).toString());
await fs.writeFile(`${out}/LICENSE.txt`, await download('LICENSE.md'));
const records = {}, manifest = [];
for (const [id, sourceId, name] of selection) {
  const source = dataset.find(entry => entry.id === sourceId);
  if (!source || source.images.length !== 2) throw new Error(`Missing pair: ${sourceId}`);
  const images = [];
  for (let frame = 0; frame < 2; frame++) {
    const bytes = await download(`exercises/${source.images[frame]}`);
    await fs.writeFile(`temp/functional-frames/${id}-${frame}.jpg`, bytes);
    images.push({ path: source.images[frame], sha256: createHash('sha256').update(bytes).digest('hex') });
  }
  records[id] = {
    sourceId, sourceName: source.name, source: 'free-exercise-db',
    equipment: id >= 274 && id <= 276 ? 'rings' : id === 277 ? 'rope' : source.equipment === 'kettlebells' ? 'kettlebell' : source.equipment,
    target: source.primaryMuscles[0], secondaryMuscles: source.secondaryMuscles,
    instructions: { en: source.instructions.filter(step => step.trim()), es: [] }
  };
  manifest.push({ id, name, sourceId, images });
}
// Encoding a sequence of source photographs, with no generated in-between poses.
execFileSync('python', ['scripts/enrichment/encode-functional-gifs.py'], { stdio: 'inherit' });
for (const item of manifest) {
  item.gifSha256 = createHash('sha256').update(await fs.readFile(`${out}/${item.id}.gif`)).digest('hex');
}
await fs.writeFile(`${out}/provenance.json`, JSON.stringify({
  repository: 'https://github.com/yuhonas/free-exercise-db', revision,
  license: 'Unlicense', licenseUrl: `${root}/LICENSE.md`,
  modifications: 'Original photographs fitted to a white 400px canvas and encoded as a two-position GIF (1.2 seconds per position). Poster is the first position.',
  exercises: manifest
}, null, 2) + '\n');
await fs.writeFile('src/data/functionalEnrichment.js', '// Generated by scripts/enrichment/build-functional.mjs. Upstream Unlicense; see public/exercise-media/functional/provenance.json.\nexport const FUNCTIONAL_ENRICHMENT = ' + JSON.stringify(records, null, 2) + ';\n');
await fs.writeFile('src/data/functionalExercises.js', '// IDs remain stable. Source mapping: scripts/enrichment/functional-selection.json\nexport const FUNCTIONAL_IDS = ' + JSON.stringify(selection.map(row => row[0])) + ';\nexport const FUNCTIONAL_EQUIPMENT = ' + JSON.stringify(Object.fromEntries(Object.entries(records).map(([id, record]) => [id, record.equipment])), null, 2) + ';\n');
console.log(`Built ${selection.length} GIFs and pinned source records.`);
